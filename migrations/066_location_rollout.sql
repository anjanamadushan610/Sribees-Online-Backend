-- =============================================================================
-- 066 - Location rollout: provinces and districts unlock, postal areas go live
-- =============================================================================
--
-- SRIBEESonline opens district by district (it starts with ~20 postal areas in
-- Kalutara), so where a customer may pick an address from is now three
-- switches, all owned by the Super Admin (Settings > Service Areas):
--
--   province unlocked  ->  district unlocked  ->  postal area active
--
-- A postal area is active when it is mapped to a branch and that mapping is
-- active (post_office_branch_mapping.is_active, unchanged). The customer's
-- address pickers and the address->branch resolution at checkout both apply
-- all three, so a locked district is neither offered nor served. Locked
-- provinces and districts are still listed to the app, marked unavailable, and
-- it shows them as "Coming soon".
--
-- REPLAYED ON EVERY DEPLOY (deploy-backend-ec2.yml runs every migrations/*.sql
-- in order). Everything here is IF NOT EXISTS / ON CONFLICT DO NOTHING, so the
-- initial unlock state below is written ONCE and an admin's later choices are
-- never reset by a deploy.
--
-- Also seeds the national postal city directory: the 2,111 Sri Lanka Post
-- offices SribeesExpress seeds its own list from (lankapost 1.0.1, MIT,
-- captured 2026-09-11), with the same spellings, so the courier sync matches
-- them by name and district. Four names repeat across districts (Bopitiya,
-- Galpatha, Makandura, Yatiyana); post_office is UNIQUE, so the first of each
-- is kept and the rest are skipped, as the courier sync already does.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS location_provinces (
    name         VARCHAR(100) PRIMARY KEY,
    name_si      VARCHAR(150),
    name_ta      VARCHAR(150),
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    is_unlocked  BOOLEAN      NOT NULL DEFAULT FALSE,
    unlocked_at  TIMESTAMPTZ,
    updated_by   VARCHAR(255),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS location_districts (
    name         VARCHAR(100) PRIMARY KEY,
    province     VARCHAR(100) NOT NULL
                 REFERENCES location_provinces (name) ON UPDATE CASCADE,
    name_si      VARCHAR(150),
    name_ta      VARCHAR(150),
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    is_unlocked  BOOLEAN      NOT NULL DEFAULT FALSE,
    unlocked_at  TIMESTAMPTZ,
    updated_by   VARCHAR(255),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_location_districts_province
    ON location_districts (province);

COMMENT ON TABLE location_provinces IS
    'Province rollout switch. Locked provinces are shown to customers as Coming soon.';
COMMENT ON TABLE location_districts IS
    'District rollout switch. Unlocking one lets its postal areas be activated.';

