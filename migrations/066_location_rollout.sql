UPDATE post_office_directory
   SET province = regexp_replace(province, '\s+Province$', '', 'i')
 WHERE province ~* '\s+Province$';
UPDATE post_office_branch_mapping
   SET province = regexp_replace(province, '\s+Province$', '', 'i')
 WHERE province ~* '\s+Province$';
UPDATE branches
   SET province = regexp_replace(province, '\s+Province$', '', 'i')
 WHERE province ~* '\s+Province$';
UPDATE addresses
   SET province = regexp_replace(province, '\s+Province$', '', 'i')
 WHERE province ~* '\s+Province$';

