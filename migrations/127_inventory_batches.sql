CREATE TABLE IF NOT EXISTS inventory_batches (
    batch_id UUID PRIMARY KEY,
    inventory_id UUID NOT NULL REFERENCES branch_inventory(inventory_id) ON DELETE RESTRICT,
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    lot_code VARCHAR(80),
    expires_on DATE,
    quantity_received INTEGER NOT NULL CHECK (quantity_received > 0),
    remaining INTEGER NOT NULL CHECK (remaining >= 0 AND remaining <= quantity_received),
    purchase_cost NUMERIC(10,2) CHECK (purchase_cost >= 0),
    listed_price NUMERIC(10,2) NOT NULL CHECK (listed_price >= 0),
    selling_price NUMERIC(10,2) NOT NULL CHECK (selling_price >= 0 AND selling_price <= listed_price)
);
CREATE INDEX IF NOT EXISTS ix_inventory_batches_fifo ON inventory_batches (inventory_id, sequence);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS inventory_batch_id UUID REFERENCES inventory_batches(batch_id) ON DELETE RESTRICT;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS inventory_batch_label VARCHAR(80);
