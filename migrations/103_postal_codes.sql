-- =============================================================================
-- 103 - Postal codes on the postal city directory; retire two misspelt towns
-- =============================================================================
--
-- 1. post_office_directory.postal_code
--    The owner wants customers to pick "12100 | Matugama", not a bare name, and
--    the saved address to carry the code. The codes come from the same
--    `lankapost` 1.0.1 snapshot (PyPI, MIT) both SribeesExpress and migration
--    066 took the names from: all 2,111 (name, district) pairs match it one to
--    one. Matched on name AND district, because four towns share a name with
--    one in another district. A row the snapshot does not know keeps NULL.
--
-- 2. Mathugama -> Matugama, Meegahathanna -> Meegahatenna (Kalutara)
--    Migration 018 hand-typed these two before the national list existed, and
--    067's backfill switched them on because a branch mapping named them. So
--    production listed "Meegahathanna" beside "Meegahatenna" (seen 2026-11-04):
--    the same town twice, and the old spelling can never get a courier quote
--    (SribeesExpress matches names exactly). Every reference moves to the
--    official spelling: saved addresses, branches, branch mappings, and the
--    directory row (keeping "switched on" if either row had it). Orders keep
--    the address they were placed with -- history is not rewritten.
--    018 no longer seeds the old spellings, so a replay cannot bring them back.
--
-- 3. Saved addresses with no postal code get the one for their town. The app
--    never sent one, so every address so far was saved with ''. A code a
--    customer did type is never overwritten.
--
-- REPLAYED ON EVERY DEPLOY: every step is a no-op the second time.
-- =============================================================================

BEGIN;

ALTER TABLE post_office_directory
    ADD COLUMN IF NOT EXISTS postal_code VARCHAR(10);

COMMENT ON COLUMN post_office_directory.postal_code IS
    'Sri Lanka Post code for this town (lankapost 1.0.1 snapshot, migration 103). Shown beside the name in the customer picker and copied onto saved addresses.';

-- ---------------------------------------------------------------------------
-- 2. Retire the misspelt rows
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    pair RECORD;
BEGIN
    FOR pair IN
        SELECT * FROM (VALUES
            ('Mathugama',     'Matugama'),
            ('Meegahathanna', 'Meegahatenna')
        ) AS v(old_name, new_name)
    LOOP
        -- Saved addresses. The courier id is cleared so the next quote
        -- re-matches the address against the directory under the new name.
        UPDATE addresses
           SET post_office = pair.new_name,
               courier_postal_city_id = NULL
         WHERE lower(post_office) = lower(pair.old_name)
           AND lower(district) = 'kalutara';

        UPDATE branches
           SET post_office = pair.new_name
         WHERE lower(post_office) = lower(pair.old_name)
           AND lower(COALESCE(district, 'kalutara')) = 'kalutara';

        -- Branch mappings: the name is unique, so drop the old row when the
        -- official one is already mapped, otherwise rename it.
        IF EXISTS (SELECT 1 FROM post_office_branch_mapping
                    WHERE lower(post_office) = lower(pair.new_name)) THEN
            DELETE FROM post_office_branch_mapping
             WHERE lower(post_office) = lower(pair.old_name);
        ELSE
            UPDATE post_office_branch_mapping
               SET post_office = pair.new_name
             WHERE lower(post_office) = lower(pair.old_name);
        END IF;

        -- Directory: same, carrying "switched on" across.
        IF EXISTS (SELECT 1 FROM post_office_directory
                    WHERE lower(post_office) = lower(pair.new_name)) THEN
            UPDATE post_office_directory n
               SET is_launched = TRUE
             WHERE lower(n.post_office) = lower(pair.new_name)
               AND NOT n.is_launched
               AND EXISTS (SELECT 1 FROM post_office_directory o
                            WHERE lower(o.post_office) = lower(pair.old_name)
                              AND o.is_launched);
            DELETE FROM post_office_directory
             WHERE lower(post_office) = lower(pair.old_name);
        ELSE
            UPDATE post_office_directory
               SET post_office = pair.new_name
             WHERE lower(post_office) = lower(pair.old_name);
        END IF;
    END LOOP;
END $$;

