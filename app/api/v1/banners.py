"""
Public Banner API Endpoint

The home-screen carousel the mobile app renders. Branch-scoped like the rest of
the storefront: a customer sees their own branch's banners plus the
platform-wide ones, ordered by ``sort_order``.

Works for guests as well as authenticated users — guests resolve their branch
via the ``X-Device-Id`` header, the same convention as branch resolution.

Prefix "/banners" is applied by app/api/v1/router.py.
"""
from typing import Literal, Optional
from uuid import UUID

from fastapi import APIRouter, Depends, Query, Request, status
from loguru import logger
from pydantic import BaseModel, Field
from redis.asyncio import Redis
from datetime import datetime, timezone

from sqlalchemy import and_, or_, select
from sqlalchemy.dialects.postgresql import insert as pg_insert
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.v1.products import _get_branch_context_for_request
from app.config.database import get_db
from app.config.redis import get_redis
from app.core.dependencies import get_current_user_optional
from app.core.media import media_url
from app.models.banner import Banner, BannerEvent, BannerEventType

router = APIRouter(tags=["Banners"])


def _live_now():
    """
    SQL filter for "this banner's schedule says it should be on screen now".

    A NULL on either end means that end is unbounded, so a banner with no
    schedule at all is always live — which is every banner created before
    scheduling existed.

    Enforced here, in the STOREFRONT query, rather than by a job that flips
    `is_active`: a background sweep leaves a window in which an expired
    promotion is still being shown, and needs somewhere to remember the
    manager's own on/off choice so it can be restored. Filtering at read time
    has neither problem — `is_active` stays purely the manual switch.
    """
    now = datetime.now(timezone.utc)
    return and_(
        or_(Banner.starts_at.is_(None), Banner.starts_at <= now),
        or_(Banner.ends_at.is_(None), Banner.ends_at >= now),
    )


@router.get("", response_model=dict)
async def list_banners(
    request: Request,
    limit: int = Query(10, ge=1, le=30),
    db: AsyncSession = Depends(get_db),
    redis: Redis = Depends(get_redis),
    current_user=Depends(get_current_user_optional),
):
    """
    Active home-screen banners for the customer's branch.

    Returns the branch's own banners together with the platform-wide ones
    (``branch_id IS NULL``), in ``sort_order``. Returns
    ``400 NO_BRANCH_CONTEXT`` if no delivery location has been chosen yet.
    """
    context = await _get_branch_context_for_request(redis, request, current_user)
    branch_id = UUID(context["branch_id"])

    query = (
        select(Banner)
        .where(
            Banner.is_active.is_(True),
            _live_now(),
            or_(Banner.branch_id == branch_id, Banner.branch_id.is_(None)),
        )
        .order_by(Banner.sort_order, Banner.created_at)
        .limit(limit)
    )
    banners = (await db.execute(query)).scalars().all()

    return {
        "success": True,
        "data": {
            "banners": [
                {
                    "bannerId": str(b.banner_id),
                    "title": b.title,
                    "subtitle": b.subtitle,
                    "imageUrl": media_url(b.image_url),
                    # 'category' | 'product' | 'quick_sale' | null. The app
                    # routes on this; 'quick_sale' carries no targetId because
                    # it opens a fixed screen.
                    "linkType": b.link_type,
                    "targetId": str(b.target_id) if b.target_id else None,
                }
                for b in banners
            ],
            "branch": {
                "branchId": context["branch_id"],
                "branchName": context.get("branch_name"),
            },
            "total": len(banners),
        },
    }


# ============================================================================
# Impression / click tracking
# ============================================================================

class BannerEventIn(BaseModel):
    """A single tracked interaction with one banner."""

    banner_id: UUID = Field(..., alias="bannerId")
    event_type: Literal["impression", "click"] = Field(..., alias="eventType")

    class Config:
        populate_by_name = True


class BannerEventBatch(BaseModel):
    """
    A batch of events, so the carousel can flush a screenful in one request
    instead of firing a round-trip per slide.

    ``session_key`` is a per-app-launch random string generated by the client.
    It is what collapses a customer scrolling the home screen up and down into
    a single impression per banner per hour — without it, impressions inflate
    and every CTR on the marketing dashboard reads far lower than reality.
    """

    events: list[BannerEventIn] = Field(..., min_length=1, max_length=50)
    session_key: Optional[str] = Field(None, alias="sessionKey", max_length=64)

    class Config:
        populate_by_name = True


@router.post("/events", response_model=dict, status_code=status.HTTP_202_ACCEPTED)
async def track_banner_events(
    request: Request,
    payload: BannerEventBatch,
    db: AsyncSession = Depends(get_db),
    redis: Redis = Depends(get_redis),
    current_user=Depends(get_current_user_optional),
):
    """
    Record banner impressions and clicks for the customer's branch.

    Deliberately forgiving: analytics must never break the storefront, so a
    duplicate impression is dropped silently by the partial unique index
    (``ON CONFLICT DO NOTHING``) and an unknown banner id is ignored rather
    than 400ing a carousel that is merely out of date. Returns 202 with the
    number of rows actually recorded.

    The branch is resolved server-side from the caller's delivery context and
    never read from the request body, so a client cannot attribute its
    impressions to somebody else's branch and skew their dashboard.
    """
    context = await _get_branch_context_for_request(redis, request, current_user)
    branch_id = UUID(context["branch_id"])

    # Only count events for banners actually visible to this branch. Anything
    # else is a stale or forged id.
    requested_ids = {e.banner_id for e in payload.events}
    visible_ids = set(
        (
            await db.execute(
                select(Banner.banner_id).where(
                    Banner.banner_id.in_(requested_ids),
                    Banner.is_active.is_(True),
                    # A banner that has expired since the carousel was rendered
                    # must not keep accruing impressions, or its CTR keeps
                    # moving after the campaign is over.
                    _live_now(),
                    or_(Banner.branch_id == branch_id, Banner.branch_id.is_(None)),
                )
            )
        ).scalars().all()
    )

    rows = [
        {
            "banner_id": e.banner_id,
            "event_type": e.event_type,
            "branch_id": branch_id,
            "user_id": getattr(current_user, "user_id", None) if current_user else None,
            # A click is a deliberate act and is always counted, so it carries no
            # dedupe key — only impressions are collapsed per session/hour.
            "session_key": payload.session_key if e.event_type == BannerEventType.IMPRESSION.value else None,
        }
        for e in payload.events
        if e.banner_id in visible_ids
    ]

    recorded = 0
    if rows:
        result = await db.execute(
            pg_insert(BannerEvent).values(rows).on_conflict_do_nothing()
        )
        await db.commit()
        recorded = result.rowcount or 0

    ignored = len(payload.events) - len(rows)
    if ignored:
        logger.debug(f"[banners] dropped {ignored} event(s) for banners not visible to branch {branch_id}")

    return {"success": True, "data": {"recorded": recorded}}
