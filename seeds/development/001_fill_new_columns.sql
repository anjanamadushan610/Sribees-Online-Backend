-- =============================================================================
-- Development seed: fill the columns added after the demo dataset was written.
--
-- THIS DIRECTORY IS NEVER APPLIED TO PRODUCTION.
--
-- Only scripts/deploy-dev.sh reads seeds/development/, and only after the real
-- migrations. Nothing in the production pipeline looks at this path. That
-- separation is the whole point: a backfill exactly like the one below used to
-- live in migrations/055, where it ran against the production database and
-- stamped 89 real customers with invented NICs they could not then correct,
-- because the NIC is write-once. It also broke every deploy after the first.
-- Inventing identity data is a legitimate thing to do to a demo dataset and
-- never a legitimate thing to do to real customers, so it lives here.
--
-- The demo dataset (migrations 021/025/026) predates:
--   * users.nic and users.alternate_phone      (055)
--   * orders.alternate_phone, orders.return_images (055, 056)
--
-- orders.contact_phone is already backfilled by 055 itself, from the delivery
-- address, and orders.return_images is correctly NULL until someone actually
-- returns something. Only the users columns need anything here.
--
-- Idempotent and safe to re-run: every statement filters on IS NULL, and the
-- generated NICs continue from the highest one already issued rather than
-- restarting at 1. Restarting was the bug in the original: ROW_NUMBER() began
-- again on every run while selecting only the NIC-less rows, so the next user
-- to sign up and stop before the profile step was handed a number that was
-- already taken, and the unique index rejected it.
-- =============================================================================

-- --- users.nic ---------------------------------------------------------------
-- Correctly shaped 12-digit NICs in the modern format: birth year, then a
-- day-of-year, then a serial. The day-of-year here is deliberately 000, which
-- is NOT valid in a real Sri Lankan NIC -- so a value generated by this script
-- can always be told apart from a real one, by a person or by a query.
WITH next_start AS (
    SELECT COALESCE(MAX(SUBSTRING(nic FROM 5)::bigint), 0) AS n
    FROM   users
    WHERE  nic ~ '^1990000[0-9]{5}$'
),
seeded AS (
    SELECT u.user_id,
           '1990' || LPAD(
               (ns.n + ROW_NUMBER() OVER (ORDER BY u.created_at, u.user_id))::text,
               8, '0'
           ) AS nic
    FROM   users u
    CROSS  JOIN next_start ns
    WHERE  u.nic IS NULL
)
UPDATE users
SET    nic = seeded.nic
FROM   seeded
WHERE  users.user_id = seeded.user_id;

-- --- users.alternate_phone ---------------------------------------------------
-- A second number the courier can call. Derived from the account's own phone
-- so it is obviously synthetic and obviously related, and only where the
-- account has a phone to derive from.
UPDATE users
SET    alternate_phone = '07' || LPAD(
           ((RIGHT(regexp_replace(phone, '[^0-9]', '', 'g'), 7)::bigint + 1) % 10000000)::text,
           7, '0'
       )
WHERE  alternate_phone IS NULL
  AND  phone IS NOT NULL
  AND  regexp_replace(phone, '[^0-9]', '', 'g') ~ '^[0-9]{7,}$';

-- --- orders.alternate_phone --------------------------------------------------
-- Frozen at checkout in real life. Backfilled here from the customer's second
-- number so the order screens have something to render, and only for orders
-- whose customer now has one.
UPDATE orders o
SET    alternate_phone = u.alternate_phone
FROM   users u
WHERE  o.user_id = u.user_id
  AND  o.alternate_phone IS NULL
  AND  u.alternate_phone IS NOT NULL;
